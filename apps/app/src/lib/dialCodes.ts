export const DEFAULT_DIAL_ISO = 'ES'

// splits a stored e164 number back into the code that leads it and the rest
export function splitDialCode(value: string): { iso: string; national: string } {
  const match = [...DIAL_CODES]
    .sort((a, b) => b.dial.length - a.dial.length)
    .find((c) => value.startsWith(c.dial))
  if (!match) return { iso: DEFAULT_DIAL_ISO, national: value }
  return { iso: match.iso, national: value.slice(match.dial.length) }
}

// joins a dialling code and the national part into the e164 form the api expects
export function toE164(iso: string, national: string): string {
  const code = DIAL_CODES.find((c) => c.iso === iso)?.dial ?? ''
  return `${code}${national.replace(/[^0-9]/g, '')}`
}
